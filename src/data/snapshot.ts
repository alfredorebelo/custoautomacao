export function snapshotFingerprint(data: PriceSnapshot = snapshot): string {
  const body = JSON.stringify({
    id: data.id,
    entries: data.entries.map((entry) => ({
      id: entry.id,
      monthlyMinor: entry.monthlyMinor,
      annualPerMonthMinor: entry.annualPerMonthMinor,
      annualTotalMinor: entry.annualTotalMinor,
      includedUnits: entry.includedUnits,
      priceStatus: entry.priceStatus,
      currency: entry.currency,
    })),
  });
  let hash = 2166136261;
  for (let index = 0; index < body.length; index += 1) {
    hash ^= body.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0).toString(16).padStart(8, "0");
}
